def read(name: str) -> str:
    return (DATA / name).read_text(encoding="utf-8")


def make_diff(path: str, hunk_sizes: list[int], width: int = 28, status: str = "modified") -> str:
    """A synthetic git diff for ``path`` with one added-lines hunk per size."""
    header = [f"diff --git a/{path} b/{path}", "index 1111111..2222222 100644", f"--- a/{path}", f"+++ b/{path}"]
    body: list[str] = []
    start = 1
    for n, size in enumerate(hunk_sizes):
        body.append(f"@@ -{start},1 +{start},{size + 1} @@")
        body.append(" context")
        body.extend(f"+{n:02d}-{i:03d}-" + "x" * (width - 8) for i in range(size))
        start += 50
    return "\n".join(header + body) + "\n"


