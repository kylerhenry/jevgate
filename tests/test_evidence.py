def test_no_newline_marker_and_hunk_without_counts():
    text = (
        "diff --git a/x.txt b/x.txt\n--- a/x.txt\n+++ b/x.txt\n"
        "@@ -1 +1 @@\n-old\n\\ No newline at end of file\n+new\n\\ No newline at end of file\n"
    )
    (file,) = ev.parse_diff(text)
    hunk = file.hunks[0]
    assert (hunk.old_start, hunk.old_count, hunk.new_start, hunk.new_count) == (1, 1, 1, 1)
    assert hunk.lines == ["-old", "\\ No newline at end of file", "+new", "\\ No newline at end of file"]
    assert file.status == "modified"


def test_git_binary_patch_and_plain_unified_diff():
    text = "diff --git a/img.bin b/img.bin\nnew file mode 100644\nGIT binary patch\nliteral 3\nKc$~\n"
    (file,) = ev.parse_diff(text)
    assert file.status == "binary" and file.binary and file.path == "img.bin"
    plain = "--- a/one.py\n+++ b/one.py\n@@ -1,2 +1,2 @@\n-a\n+b\n c\n--- /dev/null\n+++ b/two.py\n@@ -0,0 +1 @@\n+z\n"
    files = ev.parse_diff(plain)
    assert [(f.path, f.status) for f in files] == [("one.py", "modified"), ("two.py", "added")]


def test_parse_diff_never_raises_and_keeps_unknown_lines():
    assert ev.parse_diff("") == []
    assert ev.parse_diff("not a diff\nat all\n") == []
