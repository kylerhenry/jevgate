def _git(repo: Path, *args: str) -> str:
    env = {
        **os.environ, "HOME": str(repo), "GIT_CONFIG_GLOBAL": str(repo / "no-global-config"),
        "GIT_CONFIG_NOSYSTEM": "1", "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.com",
        "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@example.com",
    }
    return subprocess.run(["git", *args], cwd=repo, check=True, capture_output=True, text=True, env=env).stdout


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    if not shutil.which("git"):
        pytest.skip("git not installed")
    _git(tmp_path, "init", "-q")
    _git(tmp_path, "symbolic-ref", "HEAD", "refs/heads/main")
    (tmp_path / "a.txt").write_text("one\ntwo\n")
    _git(tmp_path, "add", "a.txt")
    _git(tmp_path, "commit", "-q", "-m", "init")
    return tmp_path


def test_git_diff_working_tree_and_untracked(repo: Path):
    (repo / "a.txt").write_text("one\ntwo\nthree\n")
    (repo / "b.txt").write_text("new\n")
    text = ev.git_diff(repo, "HEAD")
    (file,) = ev.parse_diff(text)
    assert file.path == "a.txt" and file.status == "modified" and "+three" in file.patch
    assert ev.untracked_files(repo) == ["b.txt"]
    assert ev.git_diff(repo, "HEAD", "HEAD") == ""


def test_git_diff_merge_base_form(repo: Path):
    _git(repo, "checkout", "-q", "-b", "feature")
    (repo / "a.txt").write_text("one\ntwo\nfeature\n")
