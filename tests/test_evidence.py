def test_chunk_single_when_within_budget():
    (file,) = ev.parse_diff(make_diff("a.py", [5, 5]))
    (chunk,) = ev.chunk_file(file, 10_000)
    assert (chunk.index, chunk.total, chunk.truncated) == (1, 1, False)
    assert chunk.patch == file.patch and chunk.tokens == file.tokens


def test_chunk_greedy_whole_hunks():
    (file,) = ev.parse_diff(make_diff("a.py", [10, 10, 10, 10, 10]))
    hunk_cost = tokens(file.hunks[0].text + "\n", "code")
    header_cost = tokens(file.header + "\n", "code")
    budget = header_cost + 2 * hunk_cost + 2  # two hunks fit, three do not
    chunks = ev.chunk_file(file, budget)
    assert [c.index for c in chunks] == [1, 2, 3] and all(c.total == 3 for c in chunks)
    assert [c.patch.count("@@ -") for c in chunks] == [2, 2, 1]
    assert all(c.patch.startswith("diff --git a/a.py b/a.py\n") and "+++ b/a.py" in c.patch for c in chunks)
    assert all(not c.truncated and c.tokens <= budget for c in chunks)
    assert "+04-009-" in chunks[2].patch


def test_chunk_truncates_oversized_hunk_with_marker():
    (file,) = ev.parse_diff(make_diff("big.py", [200]))
    budget = 300
    (chunk,) = ev.chunk_file(file, budget)
    assert chunk.truncated and chunk.tokens <= budget
    lines = chunk.patch.split("\n")
    assert lines[0] == "diff --git a/big.py b/big.py" and lines[3] == "+++ b/big.py" and lines[4].startswith("@@ ")
    assert lines[-1].startswith("[... ") and lines[-1].endswith(" lines omitted ...]")
    omitted = int(lines[-1].split()[1])
    assert omitted + (len(lines) - 5) == len(file.hunks[0].lines) + 1  # hunk header + body


def test_chunk_mixed_oversized_and_small_hunks():
    (file,) = ev.parse_diff(make_diff("m.py", [3, 200, 3]))
    header_cost = tokens(file.header + "\n", "code")
    small_cost = tokens(file.hunks[0].text + "\n", "code")
    chunks = ev.chunk_file(file, header_cost + 2 * small_cost + 20)
    assert [c.truncated for c in chunks] == [False, True, False]
    assert all(c.patch.startswith("diff --git") for c in chunks)


