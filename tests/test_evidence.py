def test_filter_files_reasons():
    generated = (
        "diff --git a/gen/api_pb.py b/gen/api_pb.py\nnew file mode 100644\n--- /dev/null\n+++ b/gen/api_pb.py\n"
        "@@ -0,0 +1,3 @@\n+# Code generated by protoc. DO NOT EDIT.\n+x = 1\n+y = 2\n"
    )
    not_generated = (
        "diff --git a/src/app.py b/src/app.py\n--- a/src/app.py\n+++ b/src/app.py\n"
        "@@ -10,2 +10,3 @@\n a\n+generated_at = now()\n b\n"
    )
    files = ev.parse_diff(
        read("multi.diff") + generated + not_generated
        + make_diff("package-lock.json", [3]) + make_diff("static/app.min.js", [3])
        + make_diff("dist/bundle.js", [3]) + make_diff("src/huge.py", [400])
    )
    kept, dropped = ev.filter_files(files, ignore=["*.min.js", "dist/*"], max_file_tokens=2000)
    reasons = {d["path"]: d["dropped_reason"] for d in dropped}
    assert reasons == {
        "assets/logo.png": "binary", "gen/api_pb.py": "generated", "package-lock.json": "lockfile",
        "static/app.min.js": "ignored", "dist/bundle.js": "ignored", "src/huge.py": "too_large",
    }
    assert {f.path for f in kept} == {"src/new_name.py", "src/added.py", "src/gone.py", "src/mod.py", "src/app.py"}
    huge = next(d for d in dropped if d["path"] == "src/huge.py")
    assert huge["tokens"] > 2000 and huge["status"] == "modified"


