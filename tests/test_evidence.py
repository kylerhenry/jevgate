def make_log(path: str = "t.log", *, tail_lines: int = 200, names: int = 80, blocks: int = 2) -> ev.TestLog:
    return ev.TestLog(
        path=path, tool="pytest", passed=names, failed=1, skipped=0, errors=0,
        failing=["tests/t.py::test_zero"],
        failing_blocks=["\n".join(f"block{b} line {i:02d} {'y' * 16}" for i in range(10)) for b in range(blocks)],
        names=[f"test_module_alpha_case_number_{i:04d}" for i in range(names)],
        summary="1 failed, 80 passed in 1.0s",
        tail="\n".join(f"tail line {i:03d} " + "z" * 46 for i in range(tail_lines)),
        sha256="0" * 64, tokens=1,
    )


def state_tokens(state: dict) -> int:
    return tokens(json.dumps(state, ensure_ascii=False), "code")


def test_tests_state_merges_and_fits_without_trimming():
    log = make_log()
    state = ev.tests_state([log], 10**6)
    assert state["tool"] == "pytest" and state["counts"] == {"passed": 80, "failed": 1, "skipped": 0, "errors": 0}
    assert state["names"] == log.names and state["failing_blocks"] == log.failing_blocks and state["tail"] == log.tail
    assert state["failing"] == log.failing and state["summary"] == log.summary
    two = ev.tests_state([log, make_log("go.log")], 10**6)
    assert two["counts"]["passed"] == 160 and "--- go.log ---" in two["tail"]
    assert two["summary"].startswith("t.log: ") and two["names"] == log.names
    empty = ev.tests_state([], 100)
    assert empty["tool"] == "none" and empty["counts"]["passed"] is None and empty["names"] == []


def test_tests_state_trim_order_tail_names_blocks():
    log = make_log()
    untrimmed = ev.tests_state([log], 10**6)
    tail_cost = tokens(json.dumps(untrimmed["tail"]), "code")
    names_cost = tokens(json.dumps(untrimmed["names"]), "code")
    blocks_cost = tokens(json.dumps(untrimmed["failing_blocks"]), "code")
    assert tail_cost > 3 * names_cost > 3 * blocks_cost  # sizes chosen so each stage is distinct

    only_tail = ev.tests_state([log], 1600)
    assert state_tokens(only_tail) <= 1600
    assert only_tail["tail"].startswith("[... ") and "lines trimmed ...]" in only_tail["tail"]
    assert only_tail["tail"].endswith(log.tail.splitlines()[-1])
    assert only_tail["names"] == log.names and only_tail["failing_blocks"] == log.failing_blocks

    tail_and_names = ev.tests_state([log], 700)
    assert state_tokens(tail_and_names) <= 700
    assert tail_and_names["tail"] == "[... 200 lines trimmed ...]"
    assert len(tail_and_names["names"]) < len(log.names) and tail_and_names["names"][-1].startswith("[... ")
    assert tail_and_names["names"][-1].endswith(" more names ...]")
    assert tail_and_names["failing_blocks"] == log.failing_blocks

    everything = ev.tests_state([log], 150)
    assert state_tokens(everything) <= 150
    assert everything["names"] == ["[... 80 more names ...]"]
    assert everything["failing_blocks"] != log.failing_blocks
    assert "lines of failure output trimmed ...]" in everything["failing_blocks"][-1]
    assert everything["failing"] == log.failing and everything["counts"] == untrimmed["counts"]


