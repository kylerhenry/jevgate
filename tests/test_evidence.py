def test_multi_file_diff_statuses_and_paths():
    files = ev.parse_diff(read("multi.diff"))
    by_path = {f.path: f for f in files}
    assert [f.path for f in files] == ["src/new_name.py", "src/added.py", "src/gone.py", "assets/logo.png", "src/mod.py"]
    renamed = by_path["src/new_name.py"]
    assert (renamed.status, renamed.old_path, len(renamed.hunks)) == ("renamed", "src/old_name.py", 1)
    assert by_path["src/added.py"].status == "added" and by_path["src/added.py"].old_path is None
    assert by_path["src/gone.py"].status == "deleted"
    binary = by_path["assets/logo.png"]
    assert binary.status == "binary" and binary.binary and binary.hunks == []
    mod = by_path["src/mod.py"]
    assert mod.status == "modified" and len(mod.hunks) == 2
    assert (mod.hunks[0].old_start, mod.hunks[0].old_count, mod.hunks[0].new_start, mod.hunks[0].new_count) == (10, 7, 10, 8)
    assert mod.hunks[0].header.endswith("@@ def compute(x):")
    assert mod.hunks[0].lines[2] == "+    b = a * 3"
    assert mod.tokens == tokens(mod.patch, "code")
    assert "".join(f.patch for f in files).count("diff --git") == 5


