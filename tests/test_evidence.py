def valid_doc() -> dict:
    return {
        "ticket": {"title": "Add login", "why": "Users need it", "what": "A form", "acceptance": ["Users can log in"]},
        "diff": {"base": "main", "head": None, "text": "diff --git a/x b/x\n"},
        "files_after": [{"path": "x.py", "range": [1, 3], "text": "a\nb\nc"}],
        "tests": [{"path": "t.log", "text": "1 passed", "sha256": hashlib.sha256(b"1 passed").hexdigest()}],
    }


def test_validate_delivery_accepts_valid_and_minimal():
    assert validate_delivery(valid_doc()) == []
    assert validate_delivery({"ticket": {"title": "T"}, "diff": {"text": ""}}) == []


def test_validate_delivery_lists_problems():
    assert validate_delivery([]) == ["delivery input must be a JSON object"]
    bad = {
        "ticket": {"title": " ", "why": 3, "acceptance": "not a list"},
        "diff": {"text": 5, "base": 1},
        "files_after": [{"path": "", "text": "x", "range": [3, 1]}, "nope"],
        "tests": [{"path": "t.log", "text": "abc", "sha256": "0" * 64}, {"path": "u.log", "text": "x", "sha256": "zz"}],
    }
    problems = validate_delivery(bad)
    expected_fragments = [
        "ticket.title", "ticket.why", "ticket.acceptance", "diff.text", "diff.base",
        "files_after[0].path", "files_after[0].range", "files_after[1]",
        "tests[0].sha256: does not match", "tests[1].sha256: must be 64 hex",
    ]
    for fragment in expected_fragments:
        assert any(fragment in p for p in problems), (fragment, problems)
    assert len(problems) == len(expected_fragments)
    assert validate_delivery({"diff": {"text": ""}}) == ["ticket: missing or not an object"]


def test_normalise_delivery_fills_defaults_and_dedupes():
    doc = {
        "ticket": {"title": "  T  ", "acceptance": ["- Users can log in", "users can  log in.", "", "* Second", "SECOND", 7]},
        "diff": {"text": "d"},
        "tests": [{"path": "t.log", "text": "1 passed"}, {"path": "u.log", "text": "x", "sha256": "f" * 64}],
        "extra": {"keep": True},
    }
    out = normalise_delivery(doc)
    assert out["ticket"] == {"title": "T", "why": "", "what": "", "acceptance": ["Users can log in", "Second"]}
    assert out["diff"] == {"base": None, "head": None, "text": "d"}
    assert out["files_after"] == []
    assert out["tests"][0]["sha256"] == hashlib.sha256(b"1 passed").hexdigest()
    assert out["tests"][1]["sha256"] == "f" * 64
    assert out["extra"] == {"keep": True} and doc["ticket"]["title"] == "  T  "
    full = normalise_delivery(valid_doc())
    assert full["files_after"] == [{"path": "x.py", "range": [1, 3], "text": "a\nb\nc"}]
    assert validate_delivery(full) == []
